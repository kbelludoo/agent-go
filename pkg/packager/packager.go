package packager

import (
	"bufio"
	"bytes"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"sync"
)

// PackOptions defines rules for context packing and noise reduction.
type PackOptions struct {
	RootDir          string
	IgnoreDirs       []string
	IgnoreExtensions []string
	RemoveComments   bool
	RemoveEmptyLines bool
	MaxFileSize      int64
	IncludeTests     bool
}

// DefaultPackOptions returns sensible defaults for AI coding context.
func DefaultPackOptions(rootDir string) PackOptions {
	return PackOptions{
		RootDir: rootDir,
		IgnoreDirs: []string{
			".git", ".scratch", "node_modules", "vendor",
			"testdata", ".gemini", ".cursor", ".opencode",
			"dist", "build", "tmp", ".cache",
		},
		IgnoreExtensions: []string{
			".exe", ".dll", ".so", ".dylib", ".bin", ".tar", ".gz",
			".zip", ".png", ".jpg", ".jpeg", ".gif", ".ico", ".pdf",
			".pyc", ".db", ".sqlite",
		},
		RemoveComments:   true,
		RemoveEmptyLines: true,
		MaxFileSize:      256 * 1024, // 256 KB max per file
		IncludeTests:     false,
	}
}

// PackResult contains metrics and the compressed context.
type PackResult struct {
	Content          string  `json:"content"`
	OriginalBytes    int64   `json:"original_bytes"`
	PackedBytes      int64   `json:"packed_bytes"`
	FilesCount       int     `json:"files_count"`
	EstimatedTokens  int     `json:"estimated_tokens"`
	CompressionRatio float64 `json:"compression_ratio"`
}

var (
	singleLineCommentRe = regexp.MustCompile(`^\s*(//|#|--).*$`)
	trailingSpaceRe     = regexp.MustCompile(`[ \t]+$`)
)

// Pack scans rootDir and packs all source files into a compact, token-efficient XML format.
func Pack(opts PackOptions) (*PackResult, error) {
	if opts.RootDir == "" {
		opts.RootDir = "."
	}

	ignoreDirMap := make(map[string]bool)
	for _, d := range opts.IgnoreDirs {
		ignoreDirMap[d] = true
	}

	ignoreExtMap := make(map[string]bool)
	for _, ext := range opts.IgnoreExtensions {
		ignoreExtMap[strings.ToLower(ext)] = true
	}

	type fileItem struct {
		relPath string
		absPath string
		size    int64
	}

	var candidateFiles []fileItem
	var originalTotalBytes int64

	err := filepath.WalkDir(opts.RootDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}

		name := d.Name()
		if d.IsDir() {
			if path != opts.RootDir && (ignoreDirMap[name] || strings.HasPrefix(name, ".")) {
				return filepath.SkipDir
			}
			return nil
		}

		ext := strings.ToLower(filepath.Ext(name))
		if ignoreExtMap[ext] {
			return nil
		}

		if !opts.IncludeTests && (strings.HasSuffix(name, "_test.go") || strings.HasPrefix(name, "test_")) {
			return nil
		}

		info, err := d.Info()
		if err != nil {
			return nil
		}

		if opts.MaxFileSize > 0 && info.Size() > opts.MaxFileSize {
			return nil
		}

		rel, _ := filepath.Rel(opts.RootDir, path)
		rel = filepath.ToSlash(rel)

		candidateFiles = append(candidateFiles, fileItem{
			relPath: rel,
			absPath: path,
			size:    info.Size(),
		})
		originalTotalBytes += info.Size()
		return nil
	})

	if err != nil {
		return nil, fmt.Errorf("walk dir: %w", err)
	}

	// Concurrent file reading and pruning
	type processedFile struct {
		relPath string
		content string
		order   int
	}

	results := make([]processedFile, len(candidateFiles))
	var wg sync.WaitGroup
	workers := 8
	sem := make(chan struct{}, workers)

	for i, item := range candidateFiles {
		wg.Add(1)
		sem <- struct{}{}
		go func(idx int, it fileItem) {
			defer wg.Done()
			defer func() { <-sem }()

			data, err := os.ReadFile(it.absPath)
			if err != nil {
				return
			}

			// Check for binary content (null bytes)
			if bytes.IndexByte(data, 0) != -1 {
				return
			}

			pruned := pruneFileContent(string(data), it.relPath, opts)
			if strings.TrimSpace(pruned) == "" {
				return
			}

			results[idx] = processedFile{
				relPath: it.relPath,
				content: pruned,
				order:   idx,
			}
		}(i, item)
	}

	wg.Wait()

	// Assemble compact output
	var buf bytes.Buffer
	buf.WriteString("<!-- REPOSITORY CONTEXT GENERATED BY GO-REPOMIX -->\n\n")

	filesCount := 0
	for _, res := range results {
		if res.content == "" {
			continue
		}
		filesCount++
		buf.WriteString(fmt.Sprintf("<file path=\"%s\">\n", res.relPath))
		buf.WriteString(res.content)
		if !strings.HasSuffix(res.content, "\n") {
			buf.WriteString("\n")
		}
		buf.WriteString("</file>\n\n")
	}

	finalContent := buf.String()
	packedBytes := int64(len(finalContent))

	var ratio float64
	if originalTotalBytes > 0 {
		ratio = float64(packedBytes) / float64(originalTotalBytes)
	}

	return &PackResult{
		Content:          finalContent,
		OriginalBytes:    originalTotalBytes,
		PackedBytes:      packedBytes,
		FilesCount:       filesCount,
		EstimatedTokens:  int(packedBytes / 4),
		CompressionRatio: ratio,
	}, nil
}

func pruneFileContent(raw, path string, opts PackOptions) string {
	scanner := bufio.NewScanner(strings.NewReader(raw))
	var lines []string
	lastBlank := false

	isGo := strings.HasSuffix(path, ".go")

	for scanner.Scan() {
		line := scanner.Text()
		line = trailingSpaceRe.ReplaceAllString(line, "")
		trimmed := strings.TrimSpace(line)

		if trimmed == "" {
			if opts.RemoveEmptyLines {
				if lastBlank {
					continue // Collapse multiple blank lines
				}
				lastBlank = true
			}
			lines = append(lines, "")
			continue
		}
		lastBlank = false

		if opts.RemoveComments {
			// Skip standalone comment lines
			if isGo && strings.HasPrefix(trimmed, "//") && !strings.HasPrefix(trimmed, "//go:") {
				continue
			} else if singleLineCommentRe.MatchString(trimmed) {
				continue
			}
		}

		lines = append(lines, line)
	}

	return strings.Join(lines, "\n")
}
